// Widen os tipos-literais criados pelo `as const` para `string`, para que a
// variante PT-PT possa fornecer textos diferentes mantendo exatamente o mesmo shape.
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : { -readonly [K in keyof T]: Widen<T[K]> };

